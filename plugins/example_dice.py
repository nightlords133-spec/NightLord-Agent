import random

PLUGIN = {"name": "Кубик", "version": "1.0", "description": "Команда «брось кубик» и инструмент roll_dice для модели"}


def register(api):
    """Вызывается один раз при включении. Здесь регистрируем команды, инструменты, таймеры и события."""

    # 1. Голосовая команда. pattern проверяется (re.search) по фразе в нижнем регистре без знаков препинания.
    #    Обработчик получает исходный текст и результат поиска; вернуть можно:
    #    строку (будет озвучена), ("llm", "вопрос модели"), "" (молча) или None (команда не подошла).
    def roll(text, m):
        sides = int(m.group(1)) if m.group(1) else 6
        return f"Выпало {random.randint(1, max(2, min(sides, 1000)))}."
    api.add_command(r"^(?:брось|кинь|подбрось) кубик(?: на (\d+))?$", roll, "брось кубик [на N]")

    # 2. Инструмент для модели (нужна галочка «Разрешить модели вызывать инструменты»).
    def tool_roll(args):
        return str(random.randint(1, max(2, min(int(args.get("sides") or 6), 1000))))
    api.add_tool("roll_dice", "Бросает игральный кубик и возвращает число.",
                 {"sides": {"type": "integer", "description": "Число граней, по умолчанию 6"}}, tool_roll)

